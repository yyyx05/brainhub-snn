#!/usr/bin/env python3
"""Prepare/run a Linux-server staged real SCNN graph -> learner diagnostic.

Default action prepares sources and a dependency inventory only. No SSH,
Vivado, production-source regeneration, checkpoint substitution or warm state.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import time
from pathlib import Path

from supplement_scnn_graph_reference import GRAPH_PASS, ROOT, make_fixture

BASE = ROOT / "results/paper_evidence/supplement_20261004/rtl/scnn_graph_closure"
GRAPH_STEM = "scnn_q015_real_conv1_to_classifier_t2_same_array_v1"
LEARN_STEM = "scnn_q015_real_b4t4_forward_learn_recompute_v1"
GRAPH_TB = ROOT / f"tb/tb_unified_{GRAPH_STEM}.sv"
LEARN_TB = ROOT / f"tb/tb_unified_{LEARN_STEM}.sv"
NEW_LEARN_TOP = "tb_supplement_scnn_graph_learn"
LEARN_PASS = "SCNN_GRAPH_STAGED_LEARN_RECOMPUTE_PASS"
WARNING_FLAGS = ["-Wall", "-Wno-fatal"] + ["-Wno-" + name for name in (
    "DECLFILENAME", "PROCASSINIT", "PINCONNECTEMPTY", "PINMISSING",
    "WIDTHTRUNC", "WIDTHEXPAND", "UNUSEDSIGNAL", "UNUSEDPARAM", "BLKSEQ",
    "CMPCONST", "SYNCASYNCNET", "TIMESCALEMOD", "WIDTHCONCAT", "MULTIDRIVEN",
)]


def source_list(stem):
    runner = ROOT / f"scripts/run_verilator_{stem}.ps1"
    # Read the existing literal source inventory, never execute its Windows
    # runner or regenerate its fixture into an accepted evidence directory.
    paths = re.findall(r"'(rtl[\\/][^']+\.sv)'", runner.read_text(encoding="utf-8-sig"))
    if not paths:
        raise ValueError(f"no RTL sources in {runner}")
    return [ROOT / path.replace("\\", "/") for path in dict.fromkeys(paths)]


def learner_source():
    source = LEARN_TB.read_text(encoding="utf-8-sig")

    def edit(old, new):
        nonlocal source
        if source.count(old) != 1:
            raise ValueError(f"cannot adapt existing TB fragment: {old[:100]}")
        source = source.replace(old, new, 1)

    edit("module tb_unified_" + LEARN_STEM + ";", "module " + NEW_LEARN_TOP + ";")
    edit("localparam int BATCH = 4;", "localparam int BATCH = 1;")
    edit("localparam int TIMESTEPS = 4;", "localparam int TIMESTEPS = 2;")
    edit("logic clk = 1'b0;", "logic [15:0] expected_counts [0:3];\n    logic clk = 1'b0;")
    edit('fixture_dir =\n            "results/paper_evidence/rtl/scnn_q015_real_b4t4_forward_learn_recompute_20260928/fixture";',
         'if (!$value$plusargs("SCNN_GRAPH_FIXTURE=%s", fixture_dir))\n'
         '            $fatal(1, "SCNN_GRAPH_FIXTURE is required");\n'
         '        $readmemh($sformatf("%s/expected_counts.hex", fixture_dir), expected_counts);')
    edit("warm_code_after_11_windows_q15.hex", "initial_code_q15.hex")
    edit("warm_residual_after_11_windows_q15.hex", "initial_residual_q15.hex")
    for name in ("features_q8_8.hex", "labels.hex"):
        edit('"results/paper_evidence/rtl/scnn_q015_dataset_parity/b4t4_update_fixture/' + name + '"',
             '$sformatf("%s/' + name + '", fixture_dir)')
    edit("parameter_write_count != 300", "parameter_write_count != int'(expected_counts[0])")
    edit("changed_current_count != 16", "changed_current_count != int'(expected_counts[2])")
    edit("changed_logit_count != 16", "changed_logit_count != int'(expected_counts[3])")
    edit("learning_enable = 1'b0;", """if (perf[2].residual_writes + perf[3].residual_writes !=
                longint'(expected_counts[1]))
            $fatal(1, "cold residual writes mismatch got=%0d expected=%0d",
                perf[2].residual_writes + perf[3].residual_writes, expected_counts[1]);
        learning_enable = 1'b0;""")
    edit("parameter_write_count != writes_before_recompute ||", """perf[4].residual_writes != 0 || perf[5].residual_writes != 0 ||
                parameter_write_count != writes_before_recompute ||""")
    edit('"SCNN_Q015_REAL_B4T4_FORWARD_LEARN_RECOMPUTE_PASS samples=4 timesteps=4 features=2048 classes=11 warm_windows=11 commit_window=12 code_changes=300 changed_currents=%0d changed_logits=%0d pair_flip=1 version_increment=1 p4_commands=%0d",\n            changed_current_count, changed_logit_count, total_command_count);',
         '"' + LEARN_PASS + ' samples=1 timesteps=2 features=2048 classes=11 warm_windows=0 multiplier=640 code_changes=%0d residual_changes=%0d changed_currents=%0d changed_logits=%0d pair_flip=1 version_increment=1 p4_commands=%0d",\n'
         '            parameter_write_count, expected_counts[1], changed_current_count, changed_logit_count, total_command_count);')
    start = source.index("// Bounded real-data")
    end = source.index("module ", start)
    source = source[:start] + (
        "// Generated by supplement_scnn_graph_closure.py from the unchanged real\n"
        "// B4T4 TB. Cold B1T2, actual fullgraph output replayed across a file\n"
        "// boundary. Same magnitude rule/640 scale; not a signed-off B4 episode.\n"
    ) + source[end:]
    return source


def dependencies():
    paths = set(source_list(GRAPH_STEM) + source_list(LEARN_STEM))
    paths.update([GRAPH_TB, LEARN_TB, ROOT / "tb/tb_supplement_scnn_graph_capture.sv"])
    for name in ("supplement_scnn_graph_closure.py", "supplement_scnn_graph_reference.py",
                 "supplement_scnn_graph_host.mk", "analyze_scnn_b4t4_rtl_update_contract.py",
                 f"run_verilator_{GRAPH_STEM}.ps1", f"run_verilator_{LEARN_STEM}.ps1"):
        paths.add(ROOT / "scripts" / name)
    for bank in (*range(1, 9), 12):
        paths.add(ROOT / f"models/scnn_dvsgesture_vgg9_q0_15/bank_{bank:02d}.hex")
    for directory in (
        "results/paper_evidence/rtl/scnn_q8_8_value_input_20260926/full_frame_t1_reference",
        "results/paper_evidence/rtl/scnn_full_graph_same_array_20260927/t2_reference",
    ):
        paths.update((ROOT / directory).glob("*.hex"))
    paths.add(ROOT / "imports/scnn/datasets/DVSGesture/hardware/test_10_labels.hex")
    return sorted(paths)


def prepare(output):
    output.mkdir(parents=True, exist_ok=True)
    (output / "generated").mkdir(exist_ok=True)
    tb = output / "generated" / (NEW_LEARN_TOP + ".sv")
    tb.write_text(learner_source(), encoding="ascii")
    deps = dependencies()
    missing = [str(path.relative_to(ROOT)) for path in deps if not path.is_file()]
    if missing:
        raise FileNotFoundError("missing dependencies: " + ", ".join(missing))
    (output / "dependency_paths.txt").write_text(
        "".join(path.relative_to(ROOT).as_posix() + "\n" for path in deps), encoding="utf-8")
    for stage, paths in (
        ("graph", source_list(GRAPH_STEM) + [GRAPH_TB, ROOT / "tb/tb_supplement_scnn_graph_capture.sv"]),
        ("learner", source_list(LEARN_STEM) + [tb]),
    ):
        (output / f"{stage}_sources.f").write_text("".join('"' + path.as_posix() + '"\n' for path in paths), encoding="utf-8")
    result = {"status": "prepared_not_RTL_run", "dependency_files": len(deps),
              "generated_learner_tb": str(tb), "output": str(output),
              "scope": "two fresh simulations joined by actual DUT feature values, not same-DUT online fullgraph",
              "stages": ["graph-build", "graph-run", "learner-prepare", "learner-build", "learner-run"]}
    (output / "preparation.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return result


def run_logged(command, output, name, pass_marker=None):
    log = output / f"{name}.log"
    record = {"command": command, "cwd": str(ROOT), "status": "running"}
    record_path = output / f"{name}.json"
    # Keep failed/accepted raw logs intact; a rerun uses a new output directory.
    with log.open("x", encoding="utf-8") as handle:
        record_path.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
        started = time.monotonic()
        try:
            completed = subprocess.run(command, cwd=ROOT, stdout=handle, stderr=subprocess.STDOUT, check=False)
            record.update(exit_code=completed.returncode, wall_seconds=time.monotonic() - started)
            if completed.returncode != 0:
                raise RuntimeError(f"{name} failed with exit {completed.returncode}; see {log}")
        except BaseException as error:
            record.update(status="failed_or_interrupted", error=str(error))
            raise
        finally:
            record_path.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    if pass_marker and pass_marker not in log.read_text(encoding="utf-8", errors="replace"):
        record["status"] = "missing_functional_PASS"
        record_path.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
        raise RuntimeError(f"{name}: missing {pass_marker}")
    record["status"] = "pass" if pass_marker else "command_completed"
    record_path.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(record), flush=True)


def build(output, stage, verilator, jobs, activity_monitor=None):
    graph = stage == "graph"
    prefix = "Vscgraph" if graph else "Vsclearn"
    top = "tb_supplement_scnn_graph_capture" if graph else NEW_LEARN_TOP
    obj = output / (stage + "_obj")
    if obj.exists():
        raise FileExistsError(f"use a fresh output for source rebuild, objects exist: {obj}")
    command = [verilator, "--binary", "-j", str(jobs), "--timing", "--assert",
               "--prefix", prefix, "--top-module", top, "--Mdir", str(obj),
               *WARNING_FLAGS, "--output-groups", "4", "--output-split", "5000",
               "--output-split-cfuncs", "2000"]
    makeflags = "OPT_FAST=-O1 OPT_GLOBAL=-O1"
    if graph:
        makeflags += " -f " + str(ROOT / "scripts/supplement_scnn_graph_host.mk")
    command += ["-MAKEFLAGS", makeflags, "-f", str(output / (stage + "_sources.f"))]
    if activity_monitor:
        monitor = activity_monitor.resolve()
        if not monitor.is_relative_to(ROOT) or not monitor.is_file():
            raise FileNotFoundError(f"activity monitor must be an existing workspace file: {monitor}")
        command.append(str(monitor))
    run_logged(command, output, stage + "_build")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage", choices=("prepare", "graph-build", "graph-run", "learner-prepare", "learner-build", "learner-run", "all"), default="prepare")
    parser.add_argument("--output", type=Path, default=BASE / "server_run1")
    parser.add_argument("--verilator", default="verilator")
    parser.add_argument("--jobs", type=int, choices=range(1, 13), default=4)
    parser.add_argument("--activity-monitor", type=Path,
                        help="optional parent-owned bind monitor SV, appended to both build source lists")
    args = parser.parse_args()
    output = args.output.resolve()
    if not output.is_relative_to(BASE):
        parser.error("output must be inside the owned scnn_graph_closure result directory")
    stages = ["prepare", "graph-build", "graph-run", "learner-prepare", "learner-build", "learner-run"] if args.stage == "all" else [args.stage]
    for stage in stages:
        if stage == "prepare":
            print(json.dumps(prepare(output), indent=2), flush=True)
        elif stage.endswith("-build"):
            verilator = shutil.which(args.verilator)
            if not verilator:
                raise FileNotFoundError(args.verilator)
            build(output, stage.split("-")[0], verilator, args.jobs, args.activity_monitor)
        elif stage == "graph-run":
            if (output / "graph_capture.csv").exists():
                raise FileExistsError("capture already exists; choose a fresh output")
            run_logged([str(output / "graph_obj/Vscgraph"),
                        "+SCNN_GRAPH_CAPTURE=" + str(output / "graph_capture.csv")],
                       output, "graph_run", GRAPH_PASS)
        elif stage == "learner-prepare":
            run_record = json.loads((output / "graph_run.json").read_text(encoding="utf-8"))
            if run_record.get("status") != "pass" or run_record.get("exit_code") != 0:
                raise ValueError("graph run did not exit successfully")
            print(json.dumps(make_fixture(output / "graph_capture.csv", output / "graph_run.log", output / "fixture"), indent=2), flush=True)
        elif stage == "learner-run":
            run_logged([str(output / "learner_obj/Vsclearn"),
                        "+SCNN_GRAPH_FIXTURE=" + str(output / "fixture")],
                       output, "learner_run", LEARN_PASS)
            summary = json.loads((output / "fixture/reference_summary.json").read_text(encoding="utf-8"))
            summary["status"] = "staged_RTL_continuity_pass_not_same_DUT_online_graph"
            (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
